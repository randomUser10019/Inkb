export function boardOnCopy(count: number) {
  return `In progress · ${count} in the queue`;
}

export function sealEarnedCopy(title: string) {
  return `Badge · ${title}`;
}

export function coursesCopy(n: number) {
  if (n <= 0) return "";
  return `${n} ${n === 1 ? "course" : "courses"}`;
}

export function streakDaysCopy(n: number) {
  if (n <= 0) return COPY.noStreak;
  return n === 1 ? "1-day streak" : `${n}-day streak`;
}

